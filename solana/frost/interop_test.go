// expectHex logs got (as hex) and fails the test unless it equals want. It
// returns got as hex for the vector file.
func expectHex(t *testing.T, name string, got []byte, want string) string {
	t.Helper()
	h := hex.EncodeToString(got)
	t.Logf("  %-18s = %s", name, h)
	if h != want {
		t.Errorf("%s = %s, want %s", name, h, want)
	}
	return h
}

func mustHex(t *testing.T, s string) []byte {
	t.Helper()
	b, err := hex.DecodeString(s)
	if err != nil {
		t.Fatal(err)
	}
	return b
}

func TestInteropVector(t *testing.T) {
	var file vectorFile
	file.About = vectorsAbout

	// VECTOR 1: ScalarFromEntropy with a known input
	scalar, err := ScalarFromEntropy(mustHex(t, vectorEntropy))
	if err != nil {
		t.Fatalf("ScalarFromEntropy failed: %v", err)
	}
	t.Logf("VECTOR 1: ScalarFromEntropy(%s)", vectorEntropy)
	file.ScalarFromEntropy.Entropy = vectorEntropy
	file.ScalarFromEntropy.Scalar = expectHex(t, "scalar", EncodeScalar(scalar), vectorScalar)
	file.ScalarFromEntropy.Public = expectHex(t, "public", EncodePoint(new(edwards.Point).ScalarBaseMult(scalar)), vectorPublic)

	// A seed file holds the 12 words; Key 1 must come out of them exactly as
	// from the entropy, or wallets restored from seed files would sign with
	// another key.
	share, err := KeyShareFromMnemonic(vectorBotMnemonic)
	if err != nil {
		t.Fatal(err)
	}
	t.Logf("VECTOR 1b: KeyShareFromMnemonic")
	file.KeyShareFromMnemonic.Mnemonic = vectorBotMnemonic
	file.KeyShareFromMnemonic.Scalar = expectHex(t, "secret", EncodeScalar(share.Secret), vectorBotScalar)
	file.KeyShareFromMnemonic.Public = expectHex(t, "public", EncodePoint(share.Public), vectorBotPublic)

	// VECTOR 2: DKG with fixed entropy for both parties
	botScalar, _ := ScalarFromEntropy(mustHex(t, vectorBotEntropy))
	botPublic := new(edwards.Point).ScalarBaseMult(botScalar)
	serverScalar, _ := ScalarFromEntropy(mustHex(t, vectorServerEntropy))
	serverPublic := new(edwards.Point).ScalarBaseMult(serverScalar)
	groupKey := ComputeGroupKey(botPublic, serverPublic)

	t.Logf("VECTOR 2: DKG")
	file.DKG.BotEntropy = vectorBotEntropy
	file.DKG.BotScalar = expectHex(t, "bot_scalar", EncodeScalar(botScalar), vectorBotScalar)
	file.DKG.BotPublic = expectHex(t, "bot_public", EncodePoint(botPublic), vectorBotPublic)
	file.DKG.ServerEntropy = vectorServerEntropy
	file.DKG.ServerScalar = expectHex(t, "server_scalar", EncodeScalar(serverScalar), vectorServerScalar)
	file.DKG.ServerPublic = expectHex(t, "server_public", EncodePoint(serverPublic), vectorServerPublic)
	file.DKG.GroupKey = expectHex(t, "group_key", EncodePoint(groupKey), vectorGroupKey)

	// Signing with deterministic nonces
	message := []byte("test message for interop")

	botNonceScalar, err := new(edwards.Scalar).SetUniformBytes(mustHex(t, vectorBotNonceBytes))
	if err != nil {
		t.Fatal(err)
	}
	botNonceCommitment := new(edwards.Point).ScalarBaseMult(botNonceScalar)
	serverNonceScalar, err := new(edwards.Scalar).SetUniformBytes(mustHex(t, vectorServerNonceBytes))
	if err != nil {
		t.Fatal(err)
	}
	serverNonceCommitment := new(edwards.Point).ScalarBaseMult(serverNonceScalar)

	botNonce := &SigningNonce{Secret: botNonceScalar, Commitment: botNonceCommitment}
	botResult, err := PartialSign(message, botScalar, botNonce, serverNonceCommitment, groupKey)
	if err != nil {
		t.Fatalf("Bot PartialSign failed: %v", err)
	}

	serverNonce := &SigningNonce{Secret: serverNonceScalar, Commitment: serverNonceCommitment}
	serverResult, err := PartialSign(message, serverScalar, serverNonce, botNonceCommitment, groupKey)
	if err != nil {
		t.Fatalf("Server PartialSign failed: %v", err)
	}

	sig := AggregateSignatures(botResult.GroupNonce, botResult.PartialSig, serverResult.PartialSig)

	t.Logf("VECTOR 2: Signing")
	file.Signing.Message = expectHex(t, "message", message, vectorMessage)
	file.Signing.BotNonceBytes = vectorBotNonceBytes
	file.Signing.ServerNonceBytes = vectorServerNonceBytes
	file.Signing.BotNonceCommitment = expectHex(t, "bot_nonce_commit", EncodePoint(botNonceCommitment), vectorBotNonceCommit)
	file.Signing.ServerNonceCommitment = expectHex(t, "server_nonce_comm", EncodePoint(serverNonceCommitment), vectorServerNonceCommit)
	file.Signing.GroupNonce = expectHex(t, "group_nonce", EncodePoint(botResult.GroupNonce), vectorGroupNonce)
	file.Signing.Challenge = expectHex(t, "challenge", EncodeScalar(botResult.Challenge), vectorChallenge)
	file.Signing.BotPartialSig = expectHex(t, "bot_partial_sig", EncodeScalar(botResult.PartialSig), vectorBotPartialSig)
	file.Signing.ServerPartialSig = expectHex(t, "server_partial", EncodeScalar(serverResult.PartialSig), vectorServerPartialSig)
	file.Signing.Signature = expectHex(t, "final_signature", sig[:], vectorFinalSignature)

	if !ed25519.Verify(EncodePoint(groupKey), message, sig[:]) {
		t.Fatal("CRITICAL: Interop vector failed Ed25519 verification!")
	}

	writeOrCompareVectors(t, file)
}

// writeOrCompareVectors writes the vector file and its monorepo copies under
// -update, and otherwise fails unless each matches it. A Windows checkout
// of the public repository may have CRLF line ends, which are not a
// difference.
func writeOrCompareVectors(t *testing.T, file vectorFile) {
	t.Helper()
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(file); err != nil {
		t.Fatal(err)
	}
	data := buf.Bytes()

	paths := []string{vectorsFile}
	if inMonorepo() {
		for _, c := range monorepoCopies {
			paths = append(paths, filepath.Join(monorepoRoot, filepath.FromSlash(c)))
		}
	}
	for _, path := range paths {
		if *update {
			if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(path, data, 0o644); err != nil {
				t.Fatal(err)
			}
			continue
		}
		if got, err := os.ReadFile(path); err != nil || !bytes.Equal(bytes.ReplaceAll(got, []byte("\r\n"), []byte("\n")), data) {
			t.Errorf("%s does not match the vectors here (%v); rewrite it with: go test ./solana/frost -run TestInteropVector -update", path, err)
		}
	}
}

// inMonorepo reports whether this package sits in the Botwallet monorepo,
// next to the packages that keep copies of the vectors.
func inMonorepo() bool {
	here, err := os.Stat(".")
	if err != nil {
		return false
	}
	there, err := os.Stat(filepath.Join(monorepoRoot, "packages", "cli-go", "solana", "frost"))
	return err == nil && os.SameFile(here, there)
}

