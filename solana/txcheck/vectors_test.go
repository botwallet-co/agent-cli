// vector is one message and what the confirm response says it does.
type vector struct {
	name    string
	message func() []byte
	expect  func(e *Expectation) // changes to expectation()
	refused string               // "" means Key 1 signs; else part of the CLI's reason
}

// payment builds the server's message after edit changes the payment.
func payment(edit func(p *txchecktest.Payment)) func() []byte {
	return func() []byte {
		p := serverPayment()
		if edit != nil {
			edit(&p)
		}
		return txchecktest.BuildPayment(p).Bytes()
	}
}

// transfer is payment for the owner's signing page, which builds no fee
// transfer when there is no fee.
func transfer(edit func(p *txchecktest.Payment)) func() []byte {
	return func() []byte {
		p := serverPayment()
		if edit != nil {
			edit(&p)
		}
		return txchecktest.BuildTransfer(p).Bytes()
	}
}

// tampered builds the server's message for serverPayment, after base
// changes the payment, then edit changes the message itself.
func tampered(base func(p *txchecktest.Payment), edit func(m *txchecktest.Message)) func() []byte {
	return func() []byte {
		p := serverPayment()
		if base != nil {
			base(&p)
		}
		m := txchecktest.BuildPayment(p)
		edit(m)
		return m.Bytes()
	}
}

// devnet moves serverPayment to the devnet USDC mint.
func devnet(p *txchecktest.Payment) {
	p.Mint = devnetMint
	p.Source = txchecktest.ATA(p.Wallet, devnetMint)
	p.RecipientAccount = txchecktest.ATA(p.Recipient, devnetMint)
	p.FeeAccount = txchecktest.ATA(p.FeeCollection, devnetMint)
}

// x402 is what cmd's x402Intent reads from an x402 confirm response with
// these amount_usdc and fee_usdc, in base units.
func x402(amount, fee uint64) func(e *Expectation) {
	return func(e *Expectation) {
		e.MinAmount, e.MaxAmount, e.MaxFee = amount-9_999, amount, fee+10_000
	}
}

