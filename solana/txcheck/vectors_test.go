// serverShapes runs both server builders over every combination of open
// accounts, zero and non-zero fees, and a recipient that is the fee wallet.
// (The builders were checked byte for byte against the server's TypeScript
// for these combinations.) Combinations that give the same message are
// listed once.
func serverShapes() []vector {
	builders := []struct {
		name  string
		build func(txchecktest.Payment) *txchecktest.Message
	}{
		{"buildPaymentTransaction", txchecktest.BuildPayment},
		{"buildTransferTransaction", txchecktest.BuildTransfer},
	}
	openOrNew := map[bool]string{true: "open", false: "new"}
	var out []vector
	seen := map[string]bool{}
	for _, b := range builders {
		for _, toFeeWallet := range []bool{false, true} {
			for _, recipientOpen := range []bool{true, false} {
				for _, feeOpen := range []bool{true, false} {
					if toFeeWallet && feeOpen != recipientOpen {
						continue // one account cannot be both
					}
					for _, fee := range []uint64{250_000, 0} {
						p := serverPayment()
						p.RecipientAccountExists, p.FeeAccountExists, p.Fee = recipientOpen, feeOpen, fee
						if toFeeWallet {
							p.Recipient, p.RecipientAccount = feeCollection, p.FeeAccount
						}
						message := b.build(p).Bytes()
						if key := base64.StdEncoding.EncodeToString(message); seen[key] {
							continue
						} else {
							seen[key] = true
						}
						name := fmt.Sprintf("server shape: %s, fee %s USDC, recipient account %s", b.name, FormatUSDC(fee), openOrNew[recipientOpen])
						if !toFeeWallet {
							name += ", fee account " + openOrNew[feeOpen]
						} else {
							name += ", recipient is the fee wallet"
						}
						out = append(out, vector{name: name, message: func() []byte { return message }, expect: func(e *Expectation) {
							e.MaxFee = fee
							if toFeeWallet {
								e.Recipient = feeCollection
							}
						}})
					}
				}
			}
		}
	}
	return out
}

